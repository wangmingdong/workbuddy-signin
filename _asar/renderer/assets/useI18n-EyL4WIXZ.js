/**
* 设置当前语言
* @param locale 语言代码，如 'en', 'zh-cn'
*/
function setLocale(locale) {
	const normalizedLocale = locale.toLowerCase();
	if (messages[normalizedLocale]) currentLocale = normalizedLocale;
	else {
		console.warn(`[context-viewer i18n] Locale "${locale}" not found, falling back to ${DEFAULT_LOCALE}`);
		currentLocale = DEFAULT_LOCALE;
	}
	listeners.forEach((listener) => {
		try {
			listener(currentLocale);
		} catch (e) {
			console.error("[context-viewer i18n] Error in locale change listener:", e);
		}
	});
}
/**
* 获取当前语言
*/
function getLocale() {
	return currentLocale;
}
/**
* 获取翻译文本
* @param key 翻译键
* @param replacements 替换参数，如 { count: 5, name: 'test' }
* @returns 翻译后的文本
*/
function t(key, replacements) {
	const message = messages[currentLocale]?.[key] || messages[DEFAULT_LOCALE][key] || key;
	if (!replacements) return message;
	return message.replace(/\{(\w+)\}/g, (match, placeholder) => String(replacements[placeholder] ?? match));
}
/**
* 添加语言变更监听器
* @param listener 监听器函数
* @returns 取消监听的函数
*/
function onLocaleChange(listener) {
	listeners.add(listener);
	return () => listeners.delete(listener);
}
/**
* 获取支持的语言列表
*/
function getSupportedLocales() {
	return [{
		value: DEFAULT_LOCALE,
		label: "中文(简体)"
	}, {
		value: LOCALE_EN,
		label: "English"
	}];
}
