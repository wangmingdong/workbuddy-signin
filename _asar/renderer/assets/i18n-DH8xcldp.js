/**
* 设置当前语言
* @param locale 语言代码，如 'en', 'zh-cn'
*/
function setLocale(locale) {
	const normalizedLocale = locale.toLowerCase();
	if (messages[normalizedLocale]) currentLocale = normalizedLocale;
	else currentLocale = "zh-cn";
}
/**
* 获取当前语言
*/
function getLocale() {
	return currentLocale;
}
/**
* 获取翻译文本
* @param key 翻译键
* @param replacements 替换参数，如 { count: 5 }
* @returns 翻译后的文本
*/
function t(key, replacements) {
	const message = messages[currentLocale]?.[key] || messages["zh-cn"][key] || key;
	if (!replacements) return message;
	return message.replace(/\{(\w+)\}/g, (match, placeholder) => String(replacements[placeholder] ?? match));
}
/**
* 初始化语言设置
* 可以从浏览器或其他地方获取语言偏好
*/
function initLocale() {
	if (typeof navigator !== "undefined" && navigator.language) {
		const browserLang = navigator.language.toLowerCase();
		if (browserLang.startsWith("zh")) setLocale("zh-cn");
		else if (browserLang.startsWith("en")) setLocale("en");
	}
}
