/**
* 是否为「非用户手动创建」的系统/任务自动生成工作空间路径。
* 包含自动化兜底目录与会话默认 timestamp 目录。
*/
function isAutoGeneratedWorkspaceCwd(cwd) {
	return isSystemGeneratedAutomationCwd(cwd) || isSessionDefaultCwd(cwd);
}
/**
* input-footer 工作空间 picker：会话是否代表用户可选用的「已保留工作空间」。
*
* 优先用 session 字段判定：
* - `isPlayground === false`：含「保存到工作空间」后 `moveSession` 置位的会话
* - `isBackgroundAutomation === true`：排除自动化后台任务
* - 无 `projectId`：项目内任务不归入可选工作空间
*
* 历史数据若未回填 `isBackgroundAutomation`，仅对 `automation-*` 系统目录做兜底排除
* （不误伤「保存到工作空间」后的纯 timestamp 目录）。
*/
function isKeptWorkspaceConversation(conv) {
	if (!conv.cwd || conv.isPlayground || conv.projectId) return false;
	if (conv.isBackgroundAutomation) return false;
	if (isSystemGeneratedAutomationCwd(conv.cwd)) return false;
	return true;
}
/**
* 从会话列表提取「已保留工作空间」cwd 路径键集合，供 picker 豁免 timestamp 目录名过滤。
*/
function extractSavedWorkspacePathKeys(conversations) {
	const keys = /* @__PURE__ */ new Set();
	for (const conv of conversations) {
		if (!isKeptWorkspaceConversation(conv)) continue;
		keys.add(normalizeWorkspacePathKey(conv.cwd));
	}
	return keys;
}
/**
* 工作空间 picker 候选：是否视为用户手动创建、可展示在列表中。
*
* @param cwd 工作空间绝对路径
* @param userExplicitPaths 用户通过「新建工作空间 / 打开本地文件夹」显式添加的路径键集合
*        （键为规范化后的小写正斜杠路径，与 `normalizePathForComparison` 一致）
* @param savedWorkspacePaths 「保存到工作空间」后的会话 cwd 路径键集合（见 `extractSavedWorkspacePathKeys`）
*/
function isManualWorkspaceCwd(cwd, userExplicitPaths, savedWorkspacePaths) {
	if (!cwd) return false;
	const key = normalizeWorkspacePathKey(cwd);
	if (userExplicitPaths?.has(key)) return true;
	if (savedWorkspacePaths?.has(key)) return true;
	return !isAutoGeneratedWorkspaceCwd(cwd);
}
/**
* 判断路径是否属于 Claw（本地助理）工作空间（单一权威来源）。
*
* 匹配规则（满足任一即为 Claw 路径）：
* 1. 路径中包含 "claw" 作为独立路径段（大小写不敏感），
*    即 `claw` 前后为路径分隔符或字符串首尾。
* 2. 路径中包含 `automation-claw-` 前缀的目录段（旧版自动化任务 issue #38095
*    之前使用 `automation-claw-YYYY-MM-DD-HH-mm-ss` 作为 cwd）。
*
* 本函数是所有 Claw 路径判定的唯一入口（issue #62334），
* `conversations-context.tsx` 的 `isClawPath` 委托此函数实现。
*/
function isClawWorkspacePath(path) {
	if (!path) return false;
	const normalized = path.replace(/\\/g, "/");
	return /(?:^|\/)claw(?:\/|$)/i.test(normalized) || /(?:^|\/)automation-claw-/i.test(normalized);
}
/**
* 把 cwd 格式化为展示标签（issue #48305）。
*
* - basename 命中"系统自动生成的自动化目录"格式：
*   · 中文 i18n 渲染为「自动化任务-{时间段}」
*   · 英文 i18n 渲染为 `automation-{时间段}`（保持原前缀，等于原 basename）
*   · 已带 `automation-` 前缀的去掉冗余前缀（避免「自动化任务-automation-XXX」）
* - 其他 basename（用户自选项目 / 会话默认目录 / `Claw` / `automation-api` 等）：原样返回
*
* **纯函数实现**：所有展示触点都通过本函数（或 `getWorkspaceGroupTitle`）拿到统一展示，
* 不订阅 automation snapshot、不维护本地状态、不参与 React commit/effect 时序竞争。
*/
function formatAutomationCwdLabel(cwd, t) {
	const basename = getCwdBasename(cwd);
	if (!isSystemGeneratedAutomationBasename(basename)) return basename;
	return t("automation.cwd.label", { suffix: basename.startsWith("automation-") ? basename.slice(11) : basename });
}
/**
* 从 workspace key / cwd 生成展示标题（左侧栏 / 搜索弹窗用）。
*
* - 普通路径显示最后一级目录名
* - Windows 根盘符统一显示为大写（如 c:/ → C:）
* - `workspaceKey === 'other'` 时，优先使用 `conversation.other` i18n，缺失时回退 `Other`
* - basename 命中"系统自动生成的自动化目录"格式且传入 `t` 时展示「自动化任务-XXX」（issue #48305）
*
* 与 `formatAutomationCwdLabel` 的区别：本函数额外处理 `'other'` / 空路径 / Windows
* 盘符等 workspace key 边界情况，但加前缀的判定逻辑完全一致（均走纯函数 basename 模式判定）。
*/
function getWorkspaceGroupTitle(workspaceKey, t) {
	if (workspaceKey === "other") return t ? t("conversation.other") : "Other";
	const trimmedPath = workspaceKey.replace(/[\\/]+$/, "");
	if (!trimmedPath) return workspaceKey;
	const title = trimmedPath.split(/[\\/]/).pop() || trimmedPath;
	const normalizedTitle = title.replace(/^([a-z]):(?=[\\/]|$)/i, (_, driveLetter) => `${driveLetter.toUpperCase()}:`);
	if (t && isSystemGeneratedAutomationBasename(title)) return formatAutomationCwdLabel(workspaceKey, t);
	return normalizedTitle;
}
/**
* 对单个路径段做 percent-decoding。
*
* 必须用 `decodeURIComponent`、不能用 `decodeURI`：
* `decodeURI` 会保留 URI 保留字符（`#`、`?`、`/`、`+` 等），导致 Windows 路径中
* 真实包含的 `#`（编码为 `%23`）被还原成字面量 `%23`，最终 `shell.openPath` /
* `shell.showItemInFolder` 找不到文件（"系统找不到指定的文件 (0x2)"）。
*
* 按段解码可以避免一次性 `decodeURIComponent` 失败时整个路径回退到原串，
* 让能解码的段尽量解码。
*/
function decodePathSegments(raw) {
	if (!/%[0-9A-Fa-f]{2}/.test(raw)) return raw;
	return raw.split("/").map((segment) => {
		if (!/%[0-9A-Fa-f]{2}/.test(segment)) return segment;
		try {
			return decodeURIComponent(segment);
		} catch {
			return segment;
		}
	}).join("/");
}
/**
* 把 `file://` URI 解析成本地绝对路径。
*
* 与 `extractRelativePath` 的区别：
*   - 本函数返回**本地绝对路径**（保留盘符 / unix 根 `/`），用于传给主进程做
*     文件系统操作、shell.openPath、腾讯文档 SDK 等
*   - `extractRelativePath` 返回去掉协议头后的字符串，主要用于展示或 agent uri
*     内部相对路径
*
* 关键修复：朴素的 `uri.replace(/^file:\/\/\//, '/')` 在 Windows 上是错的：
*   - `file:///C:/Users/foo/bar.xlsx`
*   - 朴素 replace → `/C:/Users/foo/bar.xlsx`（盘符前多一个 `/`）
*   - 正确路径应是 `C:/Users/foo/bar.xlsx`
*
* 错误路径传给腾讯文档 SDK 后会拼出错误的预览 URL，导致预览空白（issue #48709）。
*
* 处理形态：
*   - macOS/Linux: `file:///Users/foo/bar.xlsx`   → `/Users/foo/bar.xlsx`
*   - Windows:    `file:///C:/Users/foo/bar.xlsx` → `C:/Users/foo/bar.xlsx`
*   - percent-decode（中文 / 空格 / `%23` → `#`）
*   - 非 file:// 输入：统一分隔符并修正 `/C:/...` 这类已剥协议的 Windows 路径
*/
function fileUriToLocalPath(uri) {
	if (!uri) return "";
	if (uri.startsWith("file://")) return stripWindowsDriveLeadingSlash(decodePathSegments(normalizeSeparators(uri.slice(7))));
	return stripWindowsDriveLeadingSlash(decodePathSegments(normalizeSeparators(uri)));
}
/**
* 从 artifact URI 中提取相对路径
*
* 支持格式：
* - agent:///workspace/path/to/file → path/to/file
* - agent://files/path/to/file → path/to/file
* - file:///path/to/file → /path/to/file
* - 普通路径 → 原样返回（Windows 反斜杠会统一为正斜杠）
*/
function extractRelativePath(uri) {
	const normalized = normalizeSeparators(uri);
	const agentMatch = normalized.match(/agent:\/\/(?:\/workspace|files)\/(.+)$/);
	if (agentMatch) return decodePathSegments(agentMatch[1]);
	if (normalized.startsWith("file://")) return fileUriToLocalPath(normalized);
	return stripWindowsDriveLeadingSlash(decodePathSegments(normalized));
}
/**
* 从 ArtifactItem 中获取文件路径
*
* 优先使用文件路径字段（uri / url），回退到 id
*/
function getArtifactFilePath(item) {
	if (item.type === "media-artifact") return item.url || void 0;
	return item.uri || item.id || void 0;
}
/**
* 从 ArtifactItem 中获取去除协议前缀后的完整文件路径（包含文件名）
*/
function getArtifactRelativePath(item) {
	const raw = getArtifactFilePath(item);
	if (!raw) return;
	return extractRelativePath(raw);
}
/**
* 从 ArtifactItem 中提取文件扩展名（不含点号）
*
* 从文件路径或 URL 中提取扩展名，如 "xlsx"、"pdf"、"png" 等
* 如果没有扩展名则返回 undefined
*/
function getArtifactFileExtension(item) {
	const raw = getArtifactFilePath(item);
	if (!raw) return;
	const relativePath = extractRelativePath(raw);
	const fileName = relativePath.slice(Math.max(relativePath.lastIndexOf("/"), relativePath.lastIndexOf("\\")) + 1);
	const dotIndex = fileName.lastIndexOf(".");
	if (dotIndex > 0 && dotIndex < fileName.length - 1) return fileName.slice(dotIndex + 1).toLowerCase();
}
